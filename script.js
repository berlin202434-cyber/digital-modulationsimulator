const bitsInput = document.getElementById("bits");
const modeInput = document.getElementById("mode");
const button = document.getElementById("simulate");
const statusEl = document.getElementById("status");
const bitDisplay = document.getElementById("bitDisplay");
const results = document.getElementById("results");
const canvas = document.getElementById("waveform");
const ctx = canvas.getContext("2d");

function setStatus(message, type = "") {
  statusEl.textContent = message;
  statusEl.className = type;
}

function drawBits(bits) {
  bitDisplay.replaceChildren();
  for (const bit of bits) {
    const el = document.createElement("span");
    el.className = "bit";
    el.textContent = bit;
    bitDisplay.appendChild(el);
  }
}

function drawWaveform(samples) {
  const w = canvas.width, h = canvas.height;
  ctx.clearRect(0, 0, w, h);
  ctx.strokeStyle = "#e4eaf2";
  ctx.lineWidth = 1;
  for (let i = 1; i < 5; i++) {
    const y = i * h / 5;
    ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(w, y); ctx.stroke();
  }
  ctx.strokeStyle = "#2563eb";
  ctx.lineWidth = 2.2;
  ctx.beginPath();
  samples.forEach((value, i) => {
    const x = i * w / Math.max(1, samples.length - 1);
    const y = h / 2 - value * (h * 0.39);
    if (i === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);
  });
  ctx.stroke();
}

button.addEventListener("click", async () => {
  const bits = bitsInput.value.trim();
  if (!/^[01]{1,64}$/.test(bits)) {
    setStatus("Enter 1–64 binary digits using only 0 and 1.", "error");
    return;
  }
  button.disabled = true;
  setStatus("Sending input to the Java backend…");
  results.textContent = "";
  try {
    const response = await fetch("/api/simulate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ bits, mode: modeInput.value })
    });
    const data = await response.json();
    if (!response.ok) throw new Error(data.error || "The backend rejected the request.");
    drawBits(data.bits);
    drawWaveform(data.samples);
    results.innerHTML = "";
    const lines = [
      `Backend: ${data.backend}`,
      `Modulation: ${data.mode}`,
      `Input bits: ${data.bits}`,
      `Bits processed: ${data.bitCount}`,
      `Samples generated by Java: ${data.samples.length}`
    ];
    lines.forEach(line => {
      const div = document.createElement("div");
      div.textContent = line;
      results.appendChild(div);
    });
    setStatus("Simulation completed by the Java backend.", "success");
  } catch (err) {
    setStatus("Backend unavailable: " + err.message + " Start the Java server and open this page through http://localhost:8080.", "error");
    results.textContent = "No simulation was performed. The frontend does not calculate fallback waveforms.";
    ctx.clearRect(0, 0, canvas.width, canvas.height);
  } finally {
    button.disabled = false;
  }
});

// Do not generate demo/fallback waveforms. Results appear only after a backend response.
